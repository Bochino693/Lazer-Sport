function Titulo($texto) {
    Write-Host ""
    Write-Host ("=" * 68) -ForegroundColor DarkCyan
    Write-Host "  $texto" -ForegroundColor Cyan
    Write-Host ("=" * 68) -ForegroundColor DarkCyan
}

function Passo($texto)  { Write-Host ""; Write-Host "-> $texto" -ForegroundColor White }
function Bom($texto)    { Write-Host "   OK   $texto" -ForegroundColor Green }
function Nada($texto)   { Write-Host "   --   $texto" -ForegroundColor DarkGray }
function Alerta($texto) { Write-Host "   !!   $texto" -ForegroundColor Yellow }
function Morrer($texto) {
    Write-Host ""
    Write-Host "ERRO: $texto" -ForegroundColor Red
    Write-Host ""
    exit 1
}

# O ErrorActionPreference volta pra "Continue" durante a chamada de
# proposito: com "Stop" ligado, o PowerShell 5.1 trata cada linha que o
# programa escreve no stderr como erro fatal -- e o git escreve o
# progresso do fetch justamente ali.
function Executar($exe, $argumentos) {
    $anterior = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    $saida = & $exe @argumentos 2>&1
    $codigo = $LASTEXITCODE
    $ErrorActionPreference = $anterior
    return @{ ok = ($codigo -eq 0); saida = $saida; codigo = $codigo }
}

function Git($argumentos) { return Executar "git" $argumentos }

function GitOuMorre($argumentos, $ondeFalhou) {
    $r = Git $argumentos
    if (-not $r.ok) {
        Write-Host ""
        $r.saida | ForEach-Object { Write-Host "   $_" -ForegroundColor DarkGray }
        Morrer $ondeFalhou
    }
    return $r.saida
}

# Hash com as quebras de linha normalizadas: um arquivo identico salvo
# com CRLF pelo Windows nao pode parecer diferente do meu.
function HashDoArquivo($caminho) {
    $bytes = [IO.File]::ReadAllBytes($caminho)
    $texto = [Text.Encoding]::UTF8.GetString($bytes)
    $texto = $texto.TrimStart([char]0xFEFF).Replace("`r`n", "`n")
    $sha = [Security.Cryptography.SHA256]::Create()
    try { $h = $sha.ComputeHash([Text.Encoding]::UTF8.GetBytes($texto)) }
    finally { $sha.Dispose() }
    return ([BitConverter]::ToString($h) -replace "-", "").ToLower()
}

