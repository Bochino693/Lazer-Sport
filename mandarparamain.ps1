function Achar-Repo($inicio) {
    if ([string]::IsNullOrWhiteSpace($inicio)) { return $null }
    $atual = $inicio
    while ($atual) {
        if ((Test-Path (Join-Path $atual "manage.py")) -and
            (Test-Path (Join-Path $atual ".git"))) {
            return $atual
        }
        $pai = Split-Path $atual -Parent
        if ($pai -eq $atual) { return $null }
        $atual = $pai
    }
    return $null
}

